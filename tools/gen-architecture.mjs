#!/usr/bin/env node
// docs/architecture.md's generated parts, and the lint that keeps its prose honest.
//
// The architecture doc is hand-written — the machine (Part 1) and one section per system (Part 2) — but two parts of it
// are FACTS that rot the day the code moves, so they are generated here and checked by tests/js/architecture.test.js:
//
//   <!-- index --> … <!-- /index -->        the systems index: every id in docs/systems.json, linked to its section
//   <!-- facts: <id> --> … <!-- /facts -->  per system: what the registry says belongs to it (verbs, rooms, people,
//                                            prompts, quests, encounters, soak counters, predicates) and, for every
//                                            function the section's prose names, the file that defines it
//
// The lint is the half that matters: every backticked `_function`, `G.field` and `ALL_CAPS` constant a section names must
// exist in the source. A doc that names a renamed function is a doc that lies, and nobody notices until they go looking.
//
//   node tools/gen-architecture.mjs           rewrite the generated parts in place
//   node tools/gen-architecture.mjs --check   exit 1 if the generated parts are stale
//   node tools/gen-architecture.mjs --lint    print every name the prose uses that the source does not define (exit 1 if any)
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { join } from "node:path";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const DOC = join(ROOT, "docs/architecture.md");
const SYS = JSON.parse(readFileSync(join(ROOT, "docs/systems.json"), "utf8"));
const JS = join(ROOT, "web/js");
const VENDORED = new Set(["data.js", "examples.js", "tokeniser.js", "thai-script.js", "wordcard.js"]);
const FILES = readdirSync(JS).filter(f => f.endsWith(".js") && !VENDORED.has(f));
const SRC = Object.fromEntries(FILES.map(f => [f, readFileSync(join(JS, f), "utf8")]));
const ALL = Object.values(SRC).join("\n");

// where a name is DEFINED: function x( / const x = / let x = / var x = (top level or not — a helper inside a pool counts)
function definedIn(name) {
  const re = new RegExp(`(?:^|[\\s;{(,])(?:function\\s+${name}\\s*\\(|(?:const|let|var)\\s+${name}\\s*=|(?:const|let|var)\\s+[^;=]*\\b${name}\\b\\s*=)`, "m");
  for (const f of FILES) if (re.test(SRC[f])) return f;
  // a destructured or comma-declared const: `const A = 1, B = 2`
  const re2 = new RegExp(`(?:const|let|var)\\s[^;\\n]*[,\\s]${name}\\s*=`, "m");
  for (const f of FILES) if (re2.test(SRC[f])) return f;
  return null;
}
// a G field exists if its full path is written somewhere, or each of its segments is a key the game writes
function fieldExists(path) {
  const p = path.replace(/\[.*$/, "").replace(/\(\)$/, "");
  if (new RegExp(p.replace(/[.$]/g, "\\$&") + "(?![\\w$])").test(ALL)) return true;
  // a nested path (G.soc.drinks) is real if its root is written as such and each deeper segment is a key the game uses;
  // a top-level field must be written literally — `G.inv` is not a field just because "inv" is a word somewhere
  const segs = p.split(".").slice(1);
  if (segs.length < 2 || !new RegExp("G\\." + segs[0] + "(?![\\w$])").test(ALL)) return false;
  return segs.slice(1).every(s => new RegExp(`[.\\s{,]${s}\\s*[:=.\\[(]|\\.${s}(?![\\w$])`).test(ALL));
}

const doc = readFileSync(DOC, "utf8");
const ids = SYS.systems.map(s => s.id);

// the sections: from <!-- system: id --> to the next ### or ## heading
function sections(text) {
  const out = {};
  const re = /<!-- system: ([\w-]+) -->/g; let m;
  while ((m = re.exec(text))) {
    const start = m.index, rest = text.slice(start);
    const end = rest.slice(1).search(/\n#{2,3} /);
    out[m[1]] = rest.slice(0, end < 0 ? undefined : end + 1);
  }
  return out;
}
function prose(sec) { return sec.replace(/<!-- facts:[\s\S]*?<!-- \/facts -->/g, ""); }
function names(sec) {
  const fns = new Set(), fields = new Set(), consts = new Set();
  for (const m of prose(sec).matchAll(/`([^`\n]+)`/g)) {
    for (const tok of m[1].split(/[\s/,]+/)) {
      const t = tok.replace(/[;:,.]+$/, "");
      let x;
      if ((x = /^(_[A-Za-z0-9_]+)(?:\(.*\))?$/.exec(t))) fns.add(x[1]);
      else if ((x = /^(G(?:\.[A-Za-z_$][\w$]*)+)/.exec(t))) fields.add(x[1]);
      else if ((x = /^([A-Z][A-Z0-9]*_[A-Z0-9_]+|[A-Z]{3,}[A-Z0-9]*)$/.exec(t))) consts.add(x[1]);
    }
  }
  return { fns: [...fns], fields: [...fields], consts: [...consts] };
}

function factsFor(id, sec) {
  const s = SYS.systems.find(x => x.id === id);
  const lines = [];
  const list = (k, label, max = 14) => { const v = (s && s[k]) || []; if (v.length) lines.push(`> **${label}:** ${v.slice(0, max).map(x => "`" + x + "`").join(" · ")}${v.length > max ? ` · and ${v.length - max} more` : ""}`); };
  lines.push(`> *Generated by \`tools/gen-architecture.mjs\` from \`docs/systems.json\` and the source — do not edit by hand.*`);
  list("verbs", "Verbs"); list("modals", "Prompts (`G.pendingChoice` and the like)"); list("quests", "Quests");
  list("encounters", "Encounters"); list("effects", "Soak counters"); list("predicates", "Predicates");
  list("npcs", "People", 12); list("rooms", "Rooms", 10);
  const { fns } = names(sec);
  const byFile = {};
  for (const f of fns) { const where = definedIn(f); if (where) (byFile[where] = byFile[where] || []).push(f); }
  const order = ["engine-core.js", "engine-encounters.js", "engine-play.js", "engine-systems.js", "engine-parser.js", "world.js"];
  const files = Object.keys(byFile).sort((a, b) => ((order.indexOf(a) + 1) || 99) - ((order.indexOf(b) + 1) || 99));
  if (files.length) lines.push(`> **Code named above, by file:** ${files.map(f => `${f} — ${byFile[f].sort().map(x => "`" + x + "`").join(", ")}`).join(" · ")}`);
  return lines.join("\n");
}

function render(text) {
  const secs = sections(text);
  let out = text.replace(/<!-- facts: ([\w-]+) -->[\s\S]*?<!-- \/facts -->/g, (all, id) => `<!-- facts: ${id} -->\n${factsFor(id, secs[id] || "")}\n<!-- /facts -->`);
  // the index: every registry id, linked to its heading
  const heads = {};
  for (const m of out.matchAll(/^### (.+)\n<!-- system: ([\w-]+) -->/gm)) heads[m[2]] = m[1];
  const slug = h => h.toLowerCase().replace(/[`'’"()]/g, "").replace(/[^a-z0-9\s-]/g, "").trim().replace(/\s+/g, "-");
  const rows = SYS.systems.map(s => `| [${heads[s.id] ? heads[s.id].replace(/\s*\(`[\w-]+`\)$/, "") : s.name}](#${heads[s.id] ? slug(heads[s.id]) : ""}) | \`${s.id}\` | ${(s.note || "").split(/[.;]/)[0].slice(0, 90)} |`);
  out = out.replace(/<!-- index -->[\s\S]*?<!-- \/index -->/, `<!-- index -->\n*Generated from \`docs/systems.json\` — one row per system; the sections below are hand-written.*\n\n| System | id | note |\n|---|---|---|\n${rows.join("\n")}\n<!-- /index -->`);
  return out;
}

export function lint(text = doc) {
  const problems = [];
  const secs = sections(text);
  for (const id of ids) if (!secs[id]) problems.push(`no section for system \`${id}\``);
  for (const id of Object.keys(secs)) if (!ids.includes(id)) problems.push(`a section for \`${id}\`, which docs/systems.json does not have`);
  const counts = {}; for (const m of text.matchAll(/<!-- system: ([\w-]+) -->/g)) counts[m[1]] = (counts[m[1]] || 0) + 1;
  for (const [id, n] of Object.entries(counts)) if (n > 1) problems.push(`\`${id}\` has ${n} sections`);
  // Part 1 is held to the same standard: the whole doc's prose, not only the system sections
  const whole = names(text.replace(/<!-- index -->[\s\S]*?<!-- \/index -->/, ""));
  for (const f of whole.fns) if (!definedIn(f)) problems.push(`\`${f}\` is not defined in web/js`);
  for (const g of whole.fields) if (!fieldExists(g)) problems.push(`\`${g}\` is not a field the game writes or reads`);
  for (const c of whole.consts) if (!definedIn(c)) problems.push(`\`${c}\` is not defined in web/js`);
  return problems;
}

const argv = process.argv.slice(2);
if (import.meta.url === `file://${process.argv[1]}`) {
  if (argv.includes("--lint")) {
    const p = lint(); for (const x of p) console.log(x);
    console.log(p.length ? `${p.length} problem${p.length === 1 ? "" : "s"}` : "architecture.md: every name it uses exists");
    process.exit(p.length ? 1 : 0);
  }
  const next = render(doc);
  if (argv.includes("--check")) {
    if (next !== doc) { console.log("docs/architecture.md is stale — run node tools/gen-architecture.mjs"); process.exit(1); }
    console.log("docs/architecture.md is up to date"); process.exit(0);
  }
  writeFileSync(DOC, next);
  console.log(`docs/architecture.md: ${Object.keys(sections(next)).length} sections, index of ${ids.length}`);
}
export { render, sections };
